import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { sqliteStore,migrate } from './sqlite-store.mjs';
import { WorldService } from '../lib/world-service.ts';
import { agentConnectionState } from '../lib/agent-onboarding.ts';
const db=sqliteStore(path.join(await mkdtemp(path.join(tmpdir(),'agentnet-join-')),'test.sqlite'));migrate(db,path.resolve('drizzle'));
let now=Date.now();const w=new WorldService(db,()=>now),state=async()=>agentConnectionState(await w.view('join'));
await w.create('join','加入者');const id=(await w.row('join')).id;
assert.equal(await state(),'unauthorized');await w.issueAgentToken('join','a'.repeat(64));assert.equal(await state(),'waiting');
const driver=new WorldService(db,()=>now);assert.equal(await driver.driverOwner('a'.repeat(64)),'join');
await w.create('join','不能覆盖');assert.equal((await w.row('join')).id,id);
const o=await driver.observe('join','test',now+600000);assert(o.ready);assert.equal(await state(),'connected');
assert.equal((await w.observe('join','duplicate',now+600000)).ready,false);
await w.decide('join',o.leaseId,{action:'stay',destination:'beida',activity:'观察周围',intention:'等一会儿',reply:'',memory:'',sourceEventIds:[],waitSeconds:1800},{inputTokens:0,outputTokens:0});
await w.waitForEvents('join','test',0);assert.equal(await state(),'waiting-events');
await w.heartbeat('join','test',undefined,'model_budget');assert.equal(await state(),'model-limited');
now+=66000;assert.equal(await state(),'disconnected');
await w.heartbeat('join','test');await w.setDailyLimit('join',0);assert.equal(await state(),'limited');
await w.pause('join',true);now+=86400000;assert.equal(await state(),'paused');
await w.disconnect('join');await assert.rejects(()=>driver.waitForEvents('join','test',0),e=>e.status===401);
db.close();console.log('PASS: stable identity, actual observation, competing lease, event wait, reported model limit, stale heartbeat, campus limit, pause across day, revocation. Local synthetic clients only.');
