import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { sqliteStore,migrate } from './sqlite-store.mjs';
import { RunnerLedger,budgetDay } from './runner-ledger.mjs';
import { WorldService } from '../lib/world-service.ts';

const directory=await mkdtemp(path.join(tmpdir(),'campus-continuity-')),file=path.join(directory,'world.sqlite');
let db=sqliteStore(file);migrate(db,path.resolve('drizzle'));migrate(db,path.resolve('drizzle'));
let now=1800000000000;
const world=()=>new WorldService(db,()=>now);
await world().create('a','记忆甲','',true);await world().create('b','记忆乙','',true);
await world().issueAgentToken('a','a'.repeat(64));await world().issueAgentToken('b','b'.repeat(64));
await world().message('a','银杏树下讨论机器人。',crypto.randomUUID());
await world().message('b','银杏树下的另一人私信不能读。',crypto.randomUUID());
for(let i=0;i<70;i++)await world().message('a','普通近况 '+i,crypto.randomUUID());
assert(!(await world().view('a')).events.some(e=>e.text.includes('银杏')));
const recall=await world().recall('a','银杏',8);assert.equal(recall.memories.length,1);assert(!JSON.stringify(recall).includes('另一人'));
const lease=await world().observe('a',crypto.randomUUID(),now+600000);
const remembered=await world().recall('a','银杏',8,lease.leaseId);
const stay={action:'stay',destination:'beida',activity:'观察周围',intention:'回想之前的讨论。',reply:'',memory:'曾在银杏树下讨论机器人。',sourceEventIds:[remembered.memories[0].id],waitSeconds:90,speech:null};
await world().decide('a',lease.leaseId,stay,{inputTokens:12,outputTokens:8});
await assert.rejects(()=>world().recall('b','银杏',8,lease.leaseId),e=>e.status===409);
await world().setDailyLimit('a',2);
const second=await world().observe('a',crypto.randomUUID(),now+600000);assert(second.ready);
const calls=(await world().view('a')).character.budget.calls;
for(let i=0;i<3;i++)await world().heartbeat('a','test',second.leaseId);
assert.equal((await world().view('a')).character.budget.calls,calls,'Heartbeats do not spend decision slots');
await world().failure('a',second.leaseId,'失败也计入次数');
db.close();db=sqliteStore(file);
assert.equal((await world().view('a')).character.budget.calls,2,'Daily usage survives process/database restart');
assert((await world().recall('a','银杏')).memories.some(e=>e.kind==='memory'),'Old experiences survive disk reopen');
now+=3600001;const limited=await world().observe('a',crypto.randomUUID(),now+600000);assert.equal(limited.limitReason,'daily');
await world().issueAgentToken('a','c'.repeat(64));assert.equal((await world().observe('a',crypto.randomUUID(),now+600000)).limitReason,'daily','Reissuing credentials does not reset budget');
now+=86400000;assert((await world().observe('a',crypto.randomUUID(),now+600000)).ready);
db.close();

const ledgerFile=path.join(directory,'runner.sqlite'),limits={calls:2,tokens:1000,totalTokens:2000};
let ledger=new RunnerLedger(ledgerFile,'world#role',()=>now);
assert.throws(()=>new RunnerLedger(ledgerFile,'world#role',()=>now),/已有/);
assert(ledger.reserve('first',200,limits));ledger.settle({inputTokens:80,outputTokens:20},{leaseId:'first',decision:{action:'stay'}});ledger.close();
ledger=new RunnerLedger(ledgerFile,'world#role',()=>now);assert.equal(ledger.state.pending.phase,'decided','Saved actions survive restart without another model call');assert.equal(ledger.state.tokens,100);ledger.complete();
assert(ledger.reserve('interrupted',200,limits));ledger.close();
ledger=new RunnerLedger(ledgerFile,'world#role',()=>now);assert(ledger.state.halt);assert.equal(ledger.state.tokens,300);ledger.resume();assert(!ledger.reserve('extra',200,limits),'Restart and manual resume cannot reset daily calls');
ledger.close();now+=86400000;ledger=new RunnerLedger(ledgerFile,'world#role',()=>now);assert.equal(ledger.state.day,budgetDay(now));assert.equal(ledger.state.totalTokens,300);assert(ledger.reserve('missing-usage',200,limits));ledger.settle(null,null);assert(ledger.state.halt);assert.equal(ledger.state.totalTokens,500,'Unknown spend keeps its reservation');ledger.close();
assert.throws(()=>new RunnerLedger(ledgerFile,'other-world#role',()=>now),/绑定/);
console.log('PASS: disk-persistent history recall, source validation and isolation, non-spending heartbeats, daily cap/restart/rotation, exclusive runner, recoverable actions, durable call/token budgets, unknown-spend stop and safe resume. No real models or production accounts used.');
