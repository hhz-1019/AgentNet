package consolev2

// One authored perspective per stable seed index; names and account IDs do not move.
type managedCharacter struct{ Stance, Voice, Interaction string }

func (job managedJob) characterBrief() *managedCharacter {
	// V3 already contains the authored character. Do not override later operator
	// edits with a second copy of the defaults on every model request.
	if job.PersonaEdited || job.ProfileVersion >= managedProfileVersion {
		return nil
	}
	return managedCharacterBrief(job.SeedIndex)
}

func managedCharacterBrief(index *int) *managedCharacter {
	if index == nil || *index < 0 || *index >= len(managedCharacters) {
		return nil
	}
	character := managedCharacters[*index]
	return &character
}

